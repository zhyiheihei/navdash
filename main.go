// API handlers

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Cache-Control", "no-store")
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func (a *app) handleMe(w http.ResponseWriter, r *http.Request) {
	if s, ok := a.currentSession(r); ok {
		writeJSON(w, http.StatusOK, map[string]any{
			"authenticated": true, "username": s.User, "email": s.Email,
		})
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"authenticated": false})
}

// handleEntries serves the service card list. Unauthenticated visitors only
// see the root domain (https://zhyi.xin, the public blog); authenticated
// sessions get the full list (public + private + localhost services).
func (a *app) handleEntries(w http.ResponseWriter, r *http.Request) {
	_, authed := a.currentSession(r)
	a.entriesMu.RLock()
	entries := a.entries.Entries
	a.entriesMu.RUnlock()
	out := make([]entry, 0, len(entries))
	for _, e := range entries {
		if !authed {
			if e.Access != "public" || e.URL != "https://zhyi.xin" {
				continue
			}
		}
		out = append(out, e)
	}
	writeJSON(w, http.StatusOK, map[string]any{"entries": out})
}

// handleStatus serves the cached health probe results, filtered to exactly
// the entries the requester can see (anonymous visitors get the root blog
// only, same as /api/entries).
func (a *app) handleStatus(w http.ResponseWriter, r *http.Request) {
	_, authed := a.currentSession(r)
	all := a.probe.snapshot()
	if authed {
		writeJSON(w, http.StatusOK, map[string]any{"status": all})
		return
	}
	out := map[string]*probeStatus{}
	if st, ok := all["https://zhyi.xin"]; ok {
		out["https://zhyi.xin"] = st
	}
	writeJSON(w, http.StatusOK, map[string]any{"status": out})
}

