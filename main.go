// ---------------------------------------------------------------------------
// Configuration

type config struct {
	listen       string
	baseURL      *url.URL
	issuer       string
	clientID     string
	clientSecret string
	sessionKey   []byte
	allowedUsers map[string]bool
	entriesPath  string
}

func envOr(key, def string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return def
}

func loadConfig() (*config, error) {
	c := &config{
		listen:       envOr("NAVDASH_LISTEN", "127.0.0.1:13828"),
		issuer:       strings.TrimRight(envOr("NAVDASH_OIDC_ISSUER", ""), "/"),
		clientID:     os.Getenv("NAVDASH_OIDC_CLIENT_ID"),
		clientSecret: os.Getenv("NAVDASH_OIDC_CLIENT_SECRET"),
		entriesPath:  envOr("NAVDASH_ENTRIES", "entries.json"),
	}
	raw := envOr("NAVDASH_BASE_URL", "http://"+c.listen)
	u, err := url.Parse(raw)
	if err != nil {
		return nil, fmt.Errorf("NAVDASH_BASE_URL: %w", err)
	}
	c.baseURL = u
	if c.issuer == "" || c.clientID == "" || c.clientSecret == "" {
		return nil, errors.New("NAVDASH_OIDC_ISSUER / CLIENT_ID / CLIENT_SECRET are required")
	}
	keyHex := os.Getenv("NAVDASH_SESSION_KEY")
	if keyHex == "" {
		return nil, errors.New("NAVDASH_SESSION_KEY is required")
	}
	c.sessionKey, err = hex.DecodeString(keyHex)
	if err != nil {
		return nil, fmt.Errorf("NAVDASH_SESSION_KEY: %w", err)
	}
	if len(c.sessionKey) < 32 {
		return nil, errors.New("NAVDASH_SESSION_KEY must be at least 32 bytes of hex")
	}
	c.allowedUsers = map[string]bool{}
	if v := os.Getenv("NAVDASH_ALLOWED_USERS"); v != "" {
		for _, name := range strings.Split(v, ",") {
			if name = strings.TrimSpace(name); name != "" {
				c.allowedUsers[name] = true
			}
		}
	}
	return c, nil
}

// ---------------------------------------------------------------------------
// Signed cookie helpers (stateless HMAC-SHA256 tokens)

const (
	sessionCookie = "navdash_session"
	txCookie      = "navdash_oidc_tx"
	sessionTTL    = 7 * 24 * time.Hour
	txTTL         = 10 * time.Minute
)

func sign(key, payload []byte) string {
	m := hmac.New(sha256.New, key)
	m.Write(payload)
	return hex.EncodeToString(m.Sum(nil))
}

func seal(key []byte, v any) (string, error) {
	payload, err := json.Marshal(v)
	if err != nil {
		return "", err
	}
	b64 := base64.RawURLEncoding.EncodeToString(payload)
	return b64 + "." + sign(key, []byte(b64)), nil
}

func unseal(key []byte, cookie string, v any) error {
	b64, sig, ok := strings.Cut(cookie, ".")
	if !ok {
		return errors.New("malformed token")
	}
	expect := sign(key, []byte(b64))
	if subtle.ConstantTimeCompare([]byte(sig), []byte(expect)) != 1 {
		return errors.New("bad signature")
	}
	payload, err := base64.RawURLEncoding.DecodeString(b64)
	if err != nil {
		return err
	}
	return json.Unmarshal(payload, v)
}

type session struct {
	User    string `json:"u"`
	Email   string `json:"e"`
	Subject string `json:"sub"`
	Expire  int64  `json:"exp"`
}

func (s session) valid() bool {
	return time.Now().Unix() < s.Expire
}

// tx carries the OIDC state / PKCE verifier between login and callback,
// bound to the browser via a short lived signed cookie.
type tx struct {
	State    string `json:"state"`
	Verifier string `json:"verifier"`
	Expire   int64  `json:"exp"`
}

func setCookie(w http.ResponseWriter, name, value string, ttl time.Duration) {
	http.SetCookie(w, &http.Cookie{
		Name:     name,
		Value:    value,
		Path:     "/",
		MaxAge:   int(ttl.Seconds()),
		Expires:  time.Now().Add(ttl),
		HttpOnly: true,
		Secure:   true,
		SameSite: http.SameSiteLaxMode,
	})
}

func clearCookie(w http.ResponseWriter, name string) {
	http.SetCookie(w, &http.Cookie{
		Name: name, Value: "", Path: "/", MaxAge: -1,
		HttpOnly: true, Secure: true, SameSite: http.SameSiteLaxMode,
	})
}

func (a *app) currentSession(r *http.Request) (session, bool) {
	ck, err := r.Cookie(sessionCookie)
	if err != nil {
		return session{}, false
	}
	var s session
	if unseal(a.cfg.sessionKey, ck.Value, &s) != nil || !s.valid() {
		return session{}, false
	}
	return s, true
}

// ---------------------------------------------------------------------------
// OIDC discovery (lazy, cached, retried on demand)

type endpoints struct {
	Authorization string `json:"authorization_endpoint"`
	Token         string `json:"token_endpoint"`
	UserInfo      string `json:"userinfo_endpoint"`
}

func (a *app) discover() (*endpoints, error) {
	a.discMu.Lock()
	defer a.discMu.Unlock()
	if a.disc != nil {
		return a.disc, nil
	}
	url := a.cfg.issuer + "/.well-known/openid-configuration"
	resp, err := a.client.Get(url)
	if err != nil {
		return nil, fmt.Errorf("discovery: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("discovery: status %d", resp.StatusCode)
	}
	var ep endpoints
	if err := json.NewDecoder(resp.Body).Decode(&ep); err != nil {
		return nil, fmt.Errorf("discovery: %w", err)
	}
	a.disc = &ep
	return a.disc, nil
}

// ---------------------------------------------------------------------------
// Entries (generated at Nix evaluation time)

type entry struct {
	Name      string `json:"name"`
	Highlight string `json:"highlight"`
	Suffix    string `json:"suffix"`
	Proto     string `json:"proto"`
	URL       string `json:"url"`
	Host      string `json:"host"`
	Access    string `json:"access"`
}

type entryFile struct {
	Entries []entry `json:"entries"`
}

func loadEntries(path string) (entryFile, error) {
	var ef entryFile
	raw, err := os.ReadFile(path)
	if err != nil {
		return ef, err
	}
	if err := json.Unmarshal(raw, &ef); err != nil {
		return ef, fmt.Errorf("parse %s: %w", path, err)
	}
	return ef, nil
}

// ---------------------------------------------------------------------------
// Application

type app struct {
	cfg    *config
	client *http.Client
	disc   *endpoints
	discMu sync.Mutex

	entriesMu sync.RWMutex
	entries   entryFile

	probe *prober

	icons     *iconStore
	iconHosts map[string]bool
	bg        *bgStore

	staticFS fs.FS
	etags    map[string]string
}

func newApp(cfg *config) (*app, error) {
	ef, err := loadEntries(cfg.entriesPath)
	if err != nil {
		return nil, err
	}
	sub, err := fs.Sub(webFS, "web")
	if err != nil {
		return nil, err
	}
	a := &app{
		cfg:       cfg,
		client:    &http.Client{Timeout: 15 * time.Second},
		entries:   ef,
		probe:     newProber(probeInterval()),
		icons:     newIconStore(),
		iconHosts: map[string]bool{},
		bg:        newBGStore(),
		staticFS:  sub,
		etags:     map[string]string{},
	}
	for _, h := range entryHosts(ef.Entries) {
		a.iconHosts[h] = true
	}
	a.buildEtags()
	go a.probe.loop(ef.Entries)
	go a.icons.prefetch(entryHosts(ef.Entries))
	// Warm the hero background so the first visitor doesn't pay the fetch.
	go func() { a.bg.get() }()
	return a, nil
}

func (a *app) buildEtags() {
	_ = fs.WalkDir(a.staticFS, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		raw, err := fs.ReadFile(a.staticFS, p)
		if err != nil {
			return nil
		}
		sum := sha256.Sum256(raw)
		a.etags["/"+p] = `"` + hex.EncodeToString(sum[:16]) + `"`
		return nil
	})
}

