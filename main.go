// OIDC handlers

func randomHex(n int) (string, error) {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

func (a *app) handleLogin(w http.ResponseWriter, r *http.Request) {
	ep, err := a.discover()
	if err != nil {
		log.Printf("login: %v", err)
		http.Error(w, "OIDC provider unavailable", http.StatusBadGateway)
		return
	}
	state, err := randomHex(16)
	if err != nil {
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}
	verifier, err := randomHex(32)
	if err != nil {
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}
	// S256 code challenge
	sum := sha256.Sum256([]byte(verifier))
	challenge := base64.RawURLEncoding.EncodeToString(sum[:])

	token, err := seal(a.cfg.sessionKey, tx{
		State: state, Verifier: verifier, Expire: time.Now().Add(txTTL).Unix(),
	})
	if err != nil {
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}
	setCookie(w, txCookie, token, txTTL)

	q := url.Values{}
	q.Set("response_type", "code")
	q.Set("client_id", a.cfg.clientID)
	q.Set("redirect_uri", a.cfg.baseURL.JoinPath("/auth/callback").String())
	q.Set("scope", "openid profile email")
	q.Set("state", state)
	q.Set("code_challenge", challenge)
	q.Set("code_challenge_method", "S256")
	http.Redirect(w, r, ep.Authorization+"?"+q.Encode(), http.StatusFound)
}

type tokenResponse struct {
	AccessToken string `json:"access_token"`
	IDToken     string `json:"id_token"`
	TokenType   string `json:"token_type"`
}

type userInfoResponse struct {
	Subject       string `json:"sub"`
	PreferredUser string `json:"preferred_username"`
	Email         string `json:"email"`
}

func (a *app) handleCallback(w http.ResponseWriter, r *http.Request) {
	fail := func(msg string, code int) {
		clearCookie(w, txCookie)
		http.Error(w, msg, code)
	}
	if errStr := r.URL.Query().Get("error"); errStr != "" {
		fail("login failed: "+errStr, http.StatusUnauthorized)
		return
	}
	code := r.URL.Query().Get("code")
	state := r.URL.Query().Get("state")
	if code == "" || state == "" {
		fail("missing code/state", http.StatusBadRequest)
		return
	}
	ck, err := r.Cookie(txCookie)
	if err != nil {
		fail("login session expired, retry", http.StatusBadRequest)
		return
	}
	var t tx
	if unseal(a.cfg.sessionKey, ck.Value, &t) != nil || time.Now().Unix() > t.Expire {
		fail("login session invalid, retry", http.StatusBadRequest)
		return
	}
	if subtle.ConstantTimeCompare([]byte(t.State), []byte(state)) != 1 {
		fail("state mismatch", http.StatusBadRequest)
		return
	}
	clearCookie(w, txCookie)

	ep, err := a.discover()
	if err != nil {
		fail("OIDC provider unavailable", http.StatusBadGateway)
		return
	}
	redirectURI := a.cfg.baseURL.JoinPath("/auth/callback").String()
	form := url.Values{
		"grant_type":    {"authorization_code"},
		"code":          {code},
		"redirect_uri":  {redirectURI},
		"client_id":     {a.cfg.clientID},
		"client_secret": {a.cfg.clientSecret},
		"code_verifier": {t.Verifier},
	}
	tresp, err := a.client.PostForm(ep.Token, form)
	if err != nil {
		log.Printf("token exchange: %v", err)
		fail("token exchange failed", http.StatusBadGateway)
		return
	}
	defer tresp.Body.Close()
	if tresp.StatusCode != http.StatusOK {
		log.Printf("token exchange: status %d", tresp.StatusCode)
		fail("token exchange failed", http.StatusBadGateway)
		return
	}
	var tr tokenResponse
	if err := json.NewDecoder(tresp.Body).Decode(&tr); err != nil || tr.AccessToken == "" {
		fail("malformed token response", http.StatusBadGateway)
		return
	}

	ureq, _ := http.NewRequest(http.MethodGet, ep.UserInfo, nil)
	ureq.Header.Set("Authorization", "Bearer "+tr.AccessToken)
	uresp, err := a.client.Do(ureq)
	if err != nil {
		log.Printf("userinfo: %v", err)
		fail("userinfo failed", http.StatusBadGateway)
		return
	}
	defer uresp.Body.Close()
	if uresp.StatusCode != http.StatusOK {
		log.Printf("userinfo: status %d", uresp.StatusCode)
		fail("userinfo failed", http.StatusBadGateway)
		return
	}
	var ui userInfoResponse
	if err := json.NewDecoder(uresp.Body).Decode(&ui); err != nil || ui.Subject == "" {
		fail("malformed userinfo", http.StatusBadGateway)
		return
	}

	if len(a.cfg.allowedUsers) > 0 && !a.cfg.allowedUsers[ui.PreferredUser] {
		log.Printf("login denied for %q (not in allowlist)", ui.PreferredUser)
		fail("user not allowed", http.StatusForbidden)
		return
	}

	token, err := seal(a.cfg.sessionKey, session{
		User: ui.PreferredUser, Email: ui.Email, Subject: ui.Subject,
		Expire: time.Now().Add(sessionTTL).Unix(),
	})
	if err != nil {
		fail("internal error", http.StatusInternalServerError)
		return
	}
	setCookie(w, sessionCookie, token, sessionTTL)
	log.Printf("login ok: user=%q sub=%q", ui.PreferredUser, ui.Subject)
	http.Redirect(w, r, "/", http.StatusFound)
}

func (a *app) handleLogout(w http.ResponseWriter, r *http.Request) {
	clearCookie(w, sessionCookie)
	http.Redirect(w, r, "/", http.StatusFound)
}

