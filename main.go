// navdash: personal service portal with native OIDC (authorization code + PKCE)
// login and a static card grid generated at Nix evaluation time.
//
// Configuration is read from the environment (see config()):
//
//	NAVDASH_LISTEN           listen address (default 127.0.0.1:13828)
//	NAVDASH_BASE_URL         public origin, e.g. https://nav.zhyi.xin
//	NAVDASH_OIDC_ISSUER      OIDC issuer, e.g. https://login.zhyi.xin
//	NAVDASH_OIDC_CLIENT_ID   client id registered at the issuer
//	NAVDASH_OIDC_CLIENT_SECRET  client secret
//	NAVDASH_SESSION_KEY      hex HMAC key for signed stateless cookies
//	NAVDASH_ALLOWED_USERS    optional comma separated allowlist of
//	                        preferred_username values
//	NAVDASH_ENTRIES          path to entries.json generated by Nix
